/*
 * Writes src/<plugin>.ts for every plugin in openapi.json (the operations carrying x-polaris-plugin):
 * a factory returning one typed method per route, named after the endpoint class
 * (`ListUsersEndpoint` → `listUsers`), so `client.admin.listUsers()` is `client.GET("/admin/users")`.
 * Run by `npm run generate`; the files are checked in and drift-checked in CI.
 */
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const document = JSON.parse(readFileSync(new URL("openapi.json", root), "utf8"));
const plugins = new Map();

for (const [path, operations] of Object.entries(document.paths)) {
    for (const [method, operation] of Object.entries(operations)) {
        const plugin = operation["x-polaris-plugin"];
        if (plugin === undefined) {
            continue;
        }
        const short = operation.operationId.split("_").at(-1).replace(/Endpoint$/, "");
        const name = short.charAt(0).toLowerCase() + short.slice(1);
        const methods = plugins.get(plugin) ?? [];
        if (methods.some((existing) => existing.name === name)) {
            throw new Error(`${plugin}: two routes would be named ${name}`);
        }
        methods.push({ name, method, path, summary: operation.summary });
        plugins.set(plugin, methods);
    }
}

for (const [plugin, methods] of plugins) {
    methods.sort((a, b) => a.name.localeCompare(b.name));
    const factory = plugin;
    const type = `${plugin.charAt(0).toUpperCase()}${plugin.slice(1)}Api`;
    const lines = [
        "/* Generated by scripts/generate-namespaces.mjs from openapi.json; do not edit. */",
        'import type { Client } from "openapi-fetch";',
        'import type { paths } from "./schema.js";',
        'import type { Init } from "./namespace.js";',
        "",
        `/** The \`${plugin}\` plugin's routes as methods of \`client.${plugin}\`. */`,
        `export function ${factory}(client: Client<paths>) {`,
        "    return {",
    ];
    for (const { name, method, path, summary } of methods) {
        lines.push(`        /** ${method.toUpperCase()} ${path}: ${summary} */`);
        lines.push(`        ${name}: (...init: Init<"${path}", "${method}">) => client.${method.toUpperCase()}("${path}", ...init),`);
    }
    lines.push("    };", "}", "", `export type ${type} = ReturnType<typeof ${factory}>;`, "");
    writeFileSync(new URL(`src/${plugin}.ts`, root), lines.join("\n"));
    console.log(`src/${plugin}.ts: ${methods.length} methods`);
}
