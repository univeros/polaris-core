/*
 * Writes src/routes.ts (the route table of the agents, oauth and core routes the SDK calls: method,
 * path, input fields) and src/schema.d.ts (openapi-typescript over the same routes) from the client's
 * OpenAPI document, packages/client-ts/openapi.json, which `npm run generate` there renders from the
 * manifest. Only the paths the SDK calls are kept, so the SDK ships no dependency and a small schema.
 * Run by `npm run generate`; the files are checked in and drift-checked in CI.
 */
import { readFileSync, writeFileSync } from "node:fs";
import openapiTS, { astToString } from "openapi-typescript";

const root = new URL("../", import.meta.url);
const document = JSON.parse(readFileSync(new URL("../client-ts/openapi.json", root), "utf8"));

/** The routes the SDK calls, by path and method. */
const wanted = [
    ["/.well-known/agent-configuration", "get"],
    ["/agents/register", "post"],
    ["/agents/enroll", "post"],
    ["/agents/capabilities", "get"],
    ["/agents/grants/request", "post"],
    ["/agents/session", "get"],
    ["/agents/execute", "post"],
    ["/agents/receipts/{id}/verify", "get"],
    ["/oauth2/token", "post"],
    ["/auth/.well-known/jwks.json", "get"],
];

const paths = {};
const routes = [];
for (const [path, method] of wanted) {
    const operation = document.paths[path]?.[method];
    if (operation === undefined) {
        throw new Error(`${method.toUpperCase()} ${path} is not in openapi.json; regenerate the client first`);
    }
    paths[path] = { ...paths[path], [method]: operation };
    const short = operation.operationId.split("_").at(-1).replace(/Endpoint$/, "");
    const name = short.charAt(0).toLowerCase() + short.slice(1);
    const schema = operation.requestBody?.content?.["application/json"]?.schema ?? {};
    routes.push({
        name,
        method: method.toUpperCase(),
        path,
        summary: operation.summary,
        params: (operation.parameters ?? []).filter((parameter) => parameter.in === "path").map((parameter) => parameter.name),
        fields: Object.keys(schema.properties ?? {}),
        required: schema.required ?? [],
    });
}

const lines = [
    "/* Generated by scripts/generate.mjs from packages/client-ts/openapi.json; do not edit. */",
    "",
    "/** A route the SDK calls: its method, path, path parameters and body fields (the required ones listed). */",
    "export interface Route {",
    '    readonly method: "GET" | "POST";',
    "    readonly path: string;",
    "    readonly params: readonly string[];",
    "    readonly fields: readonly string[];",
    "    readonly required: readonly string[];",
    "}",
    "",
    "/** The agents, oauth and core routes the SDK calls, by name. */",
    "export const routes = {",
];
for (const route of routes) {
    const list = (values) => `[${values.map((value) => JSON.stringify(value)).join(", ")}]`;
    lines.push(`    /** ${route.method} ${route.path}: ${route.summary} */`);
    lines.push(`    ${route.name}: { method: "${route.method}", path: "${route.path}", params: ${list(route.params)}, fields: ${list(route.fields)}, required: ${list(route.required)} },`);
}
lines.push("} as const satisfies Record<string, Route>;", "", "export type RouteName = keyof typeof routes;", "");
writeFileSync(new URL("src/routes.ts", root), lines.join("\n"));
console.log(`src/routes.ts: ${routes.length} routes`);

const filtered = { ...document, paths, components: document.components };
const ast = await openapiTS(filtered, { exportType: false });
writeFileSync(new URL("src/schema.d.ts", root), astToString(ast));
console.log("src/schema.d.ts");
